package com.synapsemcp.rag.repository;

import static org.assertj.core.api.Assertions.assertThat;

import com.synapsemcp.auth.entity.Tenant;
import com.synapsemcp.auth.repository.TenantRepository;
import com.synapsemcp.document.entity.Document;
import com.synapsemcp.document.entity.DocumentStatus;
import com.synapsemcp.document.entity.IngestionTier;
import com.synapsemcp.document.entity.KnowledgeBase;
import com.synapsemcp.document.repository.DocumentRepository;
import com.synapsemcp.document.repository.KnowledgeBaseRepository;
import com.synapsemcp.rag.entity.Chunk;
import jakarta.persistence.EntityManager;
import java.util.Map;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.transaction.annotation.Transactional;

/**
 * Exercises the Chunk entity against a real Postgres + pgvector instance: never run before this
 * session (per docs/memory.md). Verifies vector(768) mapping, jsonb metadata, and that the
 * generated tsv column is populated by Postgres without Hibernate ever writing to it.
 * Run with: ./mvnw test -Dtest=ChunkRepositoryIT
 */
@EnabledIfEnvironmentVariable(named = "DB_USERNAME", matches = ".+")
@SpringBootTest
@Transactional
class ChunkRepositoryIT {

    @Autowired
    TenantRepository tenantRepository;
    @Autowired
    KnowledgeBaseRepository knowledgeBaseRepository;
    @Autowired
    DocumentRepository documentRepository;
    @Autowired
    ChunkRepository chunkRepository;
    @Autowired
    EntityManager entityManager;

    @Test
    void insertAndReadBackChunkWithVectorAndJsonb() {
        Tenant tenant = new Tenant();
        tenant.setName("chunk-mapping-it");
        tenant = tenantRepository.save(tenant);

        KnowledgeBase kb = new KnowledgeBase();
        kb.setTenantId(tenant.getId());
        kb = knowledgeBaseRepository.save(kb);

        Document document = new Document();
        document.setTenantId(tenant.getId());
        document.setKnowledgeBaseId(kb.getId());
        document.setName("fixture.txt");
        document.setContentType("text/plain");
        document.setFileSize(42L);
        document.setIngestionTier(IngestionTier.TIER_2_JAVA_PARSER);
        document.setStatus(DocumentStatus.INDEXED);
        document = documentRepository.save(document);

        float[] embedding = new float[Chunk.EMBEDDING_DIMENSIONS];
        for (int i = 0; i < embedding.length; i++) {
            embedding[i] = (float) Math.sin(i);
        }

        Chunk chunk = new Chunk();
        chunk.setTenantId(tenant.getId());
        chunk.setKnowledgeBaseId(kb.getId());
        chunk.setDocumentId(document.getId());
        chunk.setChunkIndex(0);
        chunk.setContent("the quick brown fox jumps over the lazy dog");
        chunk.setMetadata(Map.of("source", "chunk-mapping-it"));
        chunk.setEmbedding(embedding);

        Chunk saved = chunkRepository.save(chunk);
        entityManager.flush();
        entityManager.clear();

        Chunk reloaded = chunkRepository.findById(saved.getId()).orElseThrow();
        assertThat(reloaded.getEmbedding()).hasSize(Chunk.EMBEDDING_DIMENSIONS);
        assertThat(reloaded.getEmbedding()[1]).isCloseTo(embedding[1], org.assertj.core.data.Offset.offset(1e-5f));
        assertThat(reloaded.getMetadata()).containsEntry("source", "chunk-mapping-it");
        assertThat(reloaded.getContent()).isEqualTo("the quick brown fox jumps over the lazy dog");
        assertThat(reloaded.getCreatedAt()).isNotNull();

        // tsv is generated by Postgres and intentionally unmapped on the entity; confirm it's
        // actually populated (i.e. the generated column + GIN index are live), via a native query.
        Object tsv = entityManager.createNativeQuery("SELECT tsv FROM chunks WHERE id = ?1")
                .setParameter(1, saved.getId())
                .getSingleResult();
        assertThat(tsv.toString()).contains("fox", "dog");

        // HNSW cosine search sanity check: the chunk should be its own nearest neighbour.
        Object distance = entityManager.createNativeQuery(
                        "SELECT embedding <=> CAST(?1 AS vector) FROM chunks WHERE id = ?2")
                .setParameter(1, toVectorLiteral(embedding))
                .setParameter(2, saved.getId())
                .getSingleResult();
        assertThat(((Number) distance).doubleValue()).isCloseTo(0.0, org.assertj.core.data.Offset.offset(1e-4));
    }

    private static String toVectorLiteral(float[] vector) {
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < vector.length; i++) {
            if (i > 0) {
                sb.append(',');
            }
            sb.append(vector[i]);
        }
        return sb.append(']').toString();
    }
}
